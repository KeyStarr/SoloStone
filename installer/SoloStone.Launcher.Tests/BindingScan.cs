                    case "DeclaredMethod": summary.Sinks.Add(new Sink { Api="MethodDeclared", Args=args }); result(new Member { Kind="M", Args=args }); return;
                    case "Field": summary.Sinks.Add(new Sink { Api="Field", Args=args }); result(new Member { Kind="F", Args=args }); return;
                    case "DeclaredField": summary.Sinks.Add(new Sink { Api="FieldDeclared", Args=args }); result(new Member { Kind="F", Args=args }); return;
                    case "Property": summary.Sinks.Add(new Sink { Api="Property", Args=args }); result(new Member { Kind="P", Args=args }); return;
                    case "DeclaredProperty": summary.Sinks.Add(new Sink { Api="PropertyDeclared", Args=args }); result(new Member { Kind="P", Args=args }); return;
                    case "PropertyGetter": case "PropertySetter": case "DeclaredPropertyGetter": case "DeclaredPropertySetter": summary.Sinks.Add(new Sink { Api="Property", Args=args }); result(new Member { Kind="P", Args=args }); return;
                    case "Constructor": case "DeclaredConstructor": summary.Sinks.Add(new Sink { Api="Ctor", Args=args }); result(new Member { Kind="C", Args=args }); return;
                    case "EnumeratorMoveNext": summary.Sinks.Add(new Sink { Api="MoveNext", Args=args }); result(args.Length>0 && args[0] is Member?new Member { Kind="M", Args=((Member)args[0]).Args }:(Val)Unknown.Instance); return;
                    case "TypeByName": { var named=args[0] is Str s?new Ty { Type=s.Value }:(Val)Unknown.Instance; if(named is Ty) summary.Sinks.Add(new Sink { Api="Type", Args=new[]{named} }); result(named); return; }
