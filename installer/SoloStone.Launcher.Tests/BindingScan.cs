    static void Operands(PEReader pe,MetadataReader md,MethodDefinition def,Action<EntityHandle> token,Action<string> text,Action<FieldDefinitionHandle> fieldRead=null) {
        if(def.RelativeVirtualAddress==0) return;
        var il=pe.GetMethodBody(def.RelativeVirtualAddress).GetILReader();
        while(il.RemainingBytes>0) {
            int value=il.ReadByte(); if(value==0xFE) value=0xFE00|il.ReadByte();
            switch(Client.OpOf(value).OperandType) {
                case OperandType.InlineMethod: case OperandType.InlineField: case OperandType.InlineTok: case OperandType.InlineType: {
                    var handle=MetadataTokens.EntityHandle(il.ReadInt32());
                    if(fieldRead!=null && handle.Kind==HandleKind.FieldDefinition && value!=0x7D && value!=0x80) fieldRead((FieldDefinitionHandle)handle); // Not stfld or stsfld.
                    token(handle); break;
                }
                case OperandType.InlineString: text(md.GetUserString(MetadataTokens.UserStringHandle(il.ReadInt32()&0xFFFFFF))); break;
                case OperandType.InlineNone: break;
                case OperandType.ShortInlineBrTarget: case OperandType.ShortInlineI: case OperandType.ShortInlineVar: il.ReadByte(); break;
                case OperandType.InlineVar: il.ReadUInt16(); break;
                case OperandType.InlineI8: case OperandType.InlineR: il.ReadInt64(); break;
                case OperandType.InlineSwitch: { int n=il.ReadInt32(); for(int i=0;i<n;i++) il.ReadInt32(); break; }
                case OperandType.ShortInlineR: il.ReadSingle(); break;
                default: il.ReadInt32(); break;
            }
        }
    }
