// Builds plugin/client-bindings.txt from what the compiled plugin really binds to, for V1 (release plan 2a.3).
// Two sources, both read from the DLL and never from the source text:
//   Compiled references: every TypeRef and MemberRef into a client assembly. Complete by construction.
//   Reflection targets: every AccessTools and Type.Get* call, with a small abstract interpreter over the IL. It follows constants through
//     locals, static fields, array literals, helpers (ClientBridge.Patch, NativeUIProbe.Hook) and the NativeShop string rows.
// A site it cannot resolve is reported, and it fails the check unless plugin/client-bindings.extra.txt names the site and the targets
// it really reaches. Every row is then looked up in references/game, so a wrong guess fails here and not on a player's machine.
static class BindingScan
{
    const string ManifestHeader="# Client bindings for the V1 startup check. Generated by: tool bindings --write. Do not edit; see plugin/client-bindings.extra.txt.";
    public sealed class Scan { public SortedSet<string> BodyFailures=new SortedSet<string>(StringComparer.Ordinal); public SortedSet<string> Rows=new SortedSet<string>(StringComparer.Ordinal); public SortedSet<string> Unresolved=new SortedSet<string>(StringComparer.Ordinal);
        // A client type references/game does not hold, known only by name. Nothing here can check it, so it first meets a client in V1 itself: the live run proves these rows.
        public SortedSet<string> RuntimeOnly=new SortedSet<string>(StringComparer.Ordinal);
        public HashSet<string> Skipped=new HashSet<string>(StringComparer.Ordinal);
        // From the same scan run over only the code the plugin can reach. Null when the DLL has no plugin class to start from.
        public SortedSet<string> LiveRows; public SortedSet<string> DeadSites; public SortedSet<string> DeadMethods; public SortedSet<string> LiveMethods; public HashSet<string> LiveNames; public List<string> UnreadLookups;
        // Which method each row comes from, so a dead row can name its code.
        public Dictionary<string,SortedSet<string>> Sources=new Dictionary<string,SortedSet<string>>(StringComparer.Ordinal);
        public void From(string row,string source) { if(!Sources.TryGetValue(row,out var known)) Sources[row]=known=new SortedSet<string>(StringComparer.Ordinal); known.Add(source); } }

    // ---- One rule with the plugin's own coverage report.
    public static bool IsClientAssembly(string name) => ClientBindings.IsClientAssembly(name);

    // ---- Signatures, in the same spelling ClientBindings.Format gives a runtime Type.
    sealed class Names : ISignatureTypeProvider<string,object>
    {
        public string GetPrimitiveType(PrimitiveTypeCode code) => "System."+code;
        public string GetTypeFromDefinition(MetadataReader r,TypeDefinitionHandle h,byte kind) => TypeName(r,h);
        public string GetTypeFromReference(MetadataReader r,TypeReferenceHandle h,byte kind) => TypeName(r,h);
        public string GetTypeFromSpecification(MetadataReader r,object c,TypeSpecificationHandle h,byte kind) => r.GetTypeSpecification(h).DecodeSignature(this,c);
        public string GetSZArrayType(string e) => e+"[]";
        public string GetArrayType(string e,ArrayShape s) => e+"["+new string(',',s.Rank-1)+"]";
        public string GetByReferenceType(string e) => e+"&";
        public string GetPointerType(string e) => e+"*";
        public string GetPinnedType(string e) => e;
        public string GetGenericInstantiation(string g,ImmutableArray<string> args) => g+"<"+string.Join(",",args)+">";
        public string GetGenericTypeParameter(object c,int i) => "!"+i;
        public string GetGenericMethodParameter(object c,int i) => "!!"+i;
        public string GetFunctionPointerType(MethodSignature<string> s) => "fn";
        public string GetModifiedType(string m,string t,bool required) => t;
    }
    static readonly Names Signatures=new Names();
    public static string TypeName(MetadataReader r,TypeDefinitionHandle h) {
        var t=r.GetTypeDefinition(h);
        if(!t.GetDeclaringType().IsNil) return TypeName(r,t.GetDeclaringType())+"+"+r.GetString(t.Name);
        string space=r.GetString(t.Namespace);
        return (space.Length==0?"":space+".")+r.GetString(t.Name);
    }
    public static string TypeName(MetadataReader r,TypeReferenceHandle h) {
        var t=r.GetTypeReference(h);
        if(t.ResolutionScope.Kind==HandleKind.TypeReference) return TypeName(r,(TypeReferenceHandle)t.ResolutionScope)+"+"+r.GetString(t.Name);
        string space=r.GetString(t.Namespace);
        return (space.Length==0?"":space+".")+r.GetString(t.Name);
    }
    static string ScopeOf(MetadataReader r,TypeReferenceHandle h) {
        var scope=r.GetTypeReference(h).ResolutionScope;
        if(scope.Kind==HandleKind.TypeReference) return ScopeOf(r,(TypeReferenceHandle)scope);
        return scope.Kind==HandleKind.AssemblyReference?r.GetString(r.GetAssemblyReference((AssemblyReferenceHandle)scope).Name):null;
    }
    public static string Signature(MetadataReader md,FieldDefinition field) => field.DecodeSignature(Signatures,null);
    public static string Signature(MetadataReader md,MethodDefinition method) {
        var s=method.DecodeSignature(Signatures,null);
        return s.ReturnType+"("+string.Join(",",s.ParameterTypes)+")";
    }
    static string Row(string kind,string assembly,string type,string member,string signature) => kind+"\t"+(assembly??"*")+"\t"+type+"\t"+(member??"")+"\t"+(signature??"*");

    // ---- Abstract values of the interpreter.
    abstract class Val { }
    sealed class Unknown : Val { public static readonly Unknown Instance=new Unknown(); }
    sealed class Null : Val { }
    sealed class Str : Val { public string Value; }
    sealed class Int : Val { public int Value; }
    sealed class Token : Val { public string Type,Assembly; }
    sealed class Ty : Val { public string Type,Assembly; }                // A System.Type with a known name.
    sealed class Obj : Val { public string Type,Assembly; }               // An instance of this static type.
    sealed class Param : Val { public int Index; public bool TypeOf; public string Static; }    // A parameter, or .GetType() on one.
    sealed class Result : Val { public MethodDefinitionHandle Target; public Val[] Args; }       // What a plugin helper returns, once its summary is known.
    sealed class Arr : Val { public SortedDictionary<int,Val> Items=new SortedDictionary<int,Val>(); public bool Open; }
    sealed class Member : Val { public string Kind; public Val[] Args; }   // A lookup's answer, in terms of its arguments.
    sealed class Each : Val { public Val Items; public int Field=-1; }      // One element of a literal array, in a foreach.
    sealed class Tuple : Val { public Val[] Items; }                        // new ValueTuple<...>(...) in a literal table.
    sealed class FieldType : Val { public Val Field; }                      // member.FieldType or PropertyType.
    static bool Concrete(Val v) => v is Str || v is Ty || v is Arr a && a.Items.Values.All(Concrete) || v is Member || v is Each || v is Tuple;

    sealed class Sink { public string Api; public Val[] Args; }
    sealed class Forward { public MethodDefinitionHandle Target; public Val[] Args; }
    sealed class Summary { public List<Sink> Sinks=new List<Sink>(); public List<Forward> Calls=new List<Forward>(); public Val Return; }

    sealed class Interpreter
    {
        readonly MetadataReader md; readonly PEReader pe;
        readonly Dictionary<MethodDefinitionHandle,Summary> summaries=new Dictionary<MethodDefinitionHandle,Summary>();
        readonly Dictionary<FieldDefinitionHandle,Val> fields=new Dictionary<FieldDefinitionHandle,Val>();
        readonly Scan scan; readonly Client client; readonly HashSet<string> skip;
        string assemblyOf(string type) => client.AssemblyOf(type);
        public Interpreter(PEReader pe,MetadataReader md,Scan scan,Client client,HashSet<string> skip) { this.pe=pe; this.md=md; this.scan=scan; this.client=client; this.skip=skip; }

        HashSet<string> named;
        public void Run(HashSet<MethodDefinitionHandle> only=null,HashSet<string> namedElsewhere=null) {
            named=namedElsewhere;
            // Static constructors first, twice, so fields holding types and row tables are known wherever they are read.
            var all=md.MethodDefinitions.ToArray();
            foreach(int round in new[]{0,1}) foreach(var h in all) if(md.GetString(md.GetMethodDefinition(h).Name)==".cctor") Walk(h);
            foreach(var h in all) summaries[h]=Walk(h);
            var seen=new HashSet<string>();
            foreach(var h in all) if(only==null || only.Contains(h)) Resolve(h,null,seen,0,SiteOf(h));
            ShopRows();
        }
        static string Key(Val v) {
            switch(v) {
                case Str s: return "s:"+s.Value;
                case Ty t: return "t:"+t.Type;
                case Obj o: return "o:"+o.Type;
                case Param p: return "p:"+p.Index+(p.TypeOf?"t":"");
                case Arr a: return "["+string.Join(",",a.Items.Values.Select(Key))+"]";
                case Member m: return "m:"+m.Kind+"("+string.Join(",",m.Args.Select(Key))+")";
                case Each e: return "each:"+e.Field+":"+Key(e.Items);
                case Tuple t: return "("+string.Join(",",t.Items.Select(Key))+")";
                case FieldType f: return "ft:"+Key(f.Field);
                case Result r: return "r:"+MetadataTokens.GetToken(r.Target)+"("+string.Join(",",r.Args.Select(Key))+")";
                case Null _: return "null";
                case Int i: return "i:"+i.Value;
                default: return "?";
            }
        }
        static Val Bind(Val v,Val[] args) {
            if(v is Param p) {
                if(args==null || p.Index>=args.Length) return v;
                var bound=args[p.Index];
                if(!p.TypeOf) return bound;
                if(bound is Obj o) return new Ty { Type=o.Type, Assembly=o.Assembly };
                return bound is Param q?new Param { Index=q.Index, TypeOf=true, Static=q.Static }:Unknown.Instance;
            }
            if(v is Arr a) { var copy=new Arr { Open=a.Open }; foreach(var item in a.Items) copy.Items[item.Key]=Bind(item.Value,args); return copy; }
            if(v is Member m) return new Member { Kind=m.Kind, Args=m.Args.Select(x=>Bind(x,args)).ToArray() };
            if(v is Each e) return new Each { Items=Bind(e.Items,args), Field=e.Field };
            if(v is Tuple t) return new Tuple { Items=t.Items.Select(x=>Bind(x,args)).ToArray() };
            if(v is FieldType f) return new FieldType { Field=Bind(f.Field,args) };
            if(v is Result r) return new Result { Target=r.Target, Args=r.Args.Select(x=>Bind(x,args)).ToArray() };
            return v;
        }
        // Every concrete reading of a value: an Each is each element, and a member's field type is looked up in the client.
        IEnumerable<Val> Spread(Val v,int depth=0) {
            if(depth>8) { yield return Unknown.Instance; yield break; }
            if(v is Result call) {
                if(!summaries.TryGetValue(call.Target,out var callee) || callee.Return==null) { yield return Unknown.Instance; yield break; }
                foreach(var one in Spread(Bind(callee.Return,call.Args),depth+1)) yield return one;
                yield break;
            }
            if(v is Each e) {
                foreach(var items in Spread(e.Items,depth+1)) {
                    if(items is Arr arr && !arr.Open) foreach(var item in arr.Items.Values) { foreach(var one in Spread(Cell(item,e.Field),depth+1)) yield return one; }
                    else yield return Unknown.Instance;
                }
                yield break;
            }
            if(v is FieldType f) {
                foreach(var field in Spread(f.Field,depth+1)) {
                    var m=field as Member; var owner=m!=null && m.Args.Length>1?m.Args[0] as Ty:null; var name=m!=null && m.Args.Length>1?m.Args[1] as Str:null;
                    string found=owner!=null && name!=null?client.MemberType(owner.Type,name.Value):null;
                    yield return found!=null?new Ty { Type=found }:(Val)Unknown.Instance;
                }
                yield break;
            }
            if(v is Member member) {
                var lists=member.Args.Select(a=>Spread(a,depth+1).ToArray()).ToArray();
                foreach(var combo in Combine(lists)) yield return new Member { Kind=member.Kind, Args=combo };
                yield break;
            }
            yield return v;
        }
        // site.Type and site.Method read one row of a table together: never one row's type with another's name.
        IEnumerable<Val[]> OneRowAtATime(Val[] args,int depth=0) {
            var each=depth<6?args.Select(FirstEach).FirstOrDefault(e=>e!=null):null;
            if(each==null) { yield return args; yield break; }
            var table=Spread(each.Items).FirstOrDefault() as Arr;
            if(table==null || table.Open) { yield return args; yield break; }
            string key=Key(each.Items);
            foreach(var item in table.Items.Values)
                foreach(var row in OneRowAtATime(args.Select(a=>Pick(a,key,item)).ToArray(),depth+1)) yield return row;
        }
        // field<0 is the row itself; otherwise that cell of a tuple or a string row.
        static Val Cell(Val row,int field) {
            if(field<0) return row;
            if(row is Tuple t) return field<t.Items.Length?t.Items[field]:Unknown.Instance;
            if(row is Arr a && a.Items.TryGetValue(field,out var cell)) return cell;
            return Unknown.Instance;
        }
        static Each FirstEach(Val v) {
            switch(v) {
                case Each e: return e;
                case Member m: return m.Args.Select(FirstEach).FirstOrDefault(x=>x!=null);
                case Result r: return r.Args.Select(FirstEach).FirstOrDefault(x=>x!=null);
                case FieldType f: return FirstEach(f.Field);
                case Tuple t: return t.Items.Select(FirstEach).FirstOrDefault(x=>x!=null);
                case Arr a: return a.Items.Values.Select(FirstEach).FirstOrDefault(x=>x!=null);
                default: return null;
            }
        }
        static Val Pick(Val v,string key,Val item) {
            switch(v) {
                case Each e when Key(e.Items)==key: return Cell(item,e.Field);
                case Member m: return new Member { Kind=m.Kind, Args=m.Args.Select(x=>Pick(x,key,item)).ToArray() };
                case Result r: return new Result { Target=r.Target, Args=r.Args.Select(x=>Pick(x,key,item)).ToArray() };
                case FieldType f: return new FieldType { Field=Pick(f.Field,key,item) };
                case Tuple t: return new Tuple { Items=t.Items.Select(x=>Pick(x,key,item)).ToArray() };
                case Arr a: { var copy=new Arr { Open=a.Open }; foreach(var cell in a.Items) copy.Items[cell.Key]=Pick(cell.Value,key,item); return copy; }
                default: return v;
            }
        }
        // A parameter of a method nobody passes constants to, such as a Harmony prefix's __instance: its declared type is what we know.
        static Val Declared(Val v) {
            if(v is Param p) {
                if(p.Static==null) return Unknown.Instance;
                int at=p.Static.IndexOf('<'); string open=at<0?p.Static:p.Static.Substring(0,at);
                if(open.EndsWith("]",StringComparison.Ordinal) || open.StartsWith("!",StringComparison.Ordinal) || open=="System.Object") return Unknown.Instance;
                if(open.EndsWith("&",StringComparison.Ordinal)) open=open.Substring(0,open.Length-1);
                return p.TypeOf?(Val)new Ty { Type=open }:new Obj { Type=open };
            }
            if(v is Arr a) { var copy=new Arr { Open=a.Open }; foreach(var item in a.Items) copy.Items[item.Key]=Declared(item.Value); return copy; }
            return v;
        }
        static IEnumerable<Val[]> Combine(Val[][] lists) {
            IEnumerable<Val[]> rows=new[]{new Val[0]};
            foreach(var list in lists) rows=rows.SelectMany(row=>list.Select(one=>row.Concat(new[]{one}).ToArray())).ToArray();
            return rows;
        }
        // args null: this method as a root. A sink on a parameter waits for its callers. A method nobody calls with constants stays unresolved.
        void Resolve(MethodDefinitionHandle h,Val[] args,HashSet<string> seen,int depth,string origin) {
            if(depth>12 || !summaries.TryGetValue(h,out var s)) return;
            string key=MetadataTokens.GetToken(h)+"|"+(args==null?"root":string.Join("|",args.Select(Key)));
            if(!seen.Add(key)) return;
            foreach(var sink in s.Sinks) {
                var bound=sink.Args.Select(a=>Bind(a,args)).ToArray();
                if(args==null && sink.Args.Any(HasParam) && Helper(h)) continue; // A helper's own body: its callers bind it.
                if(args==null) bound=bound.Select(Declared).ToArray();
                // The frame that lost the value is the one to name: a sink of this method's own unknowns is reported here, not at whoever called it.
                string where=args==null || !sink.Args.Any(HasParam)?SiteOf(h):origin;
                foreach(var row in OneRowAtATime(bound))
                    foreach(var combo in Combine(row.Select(a=>Spread(a).ToArray()).ToArray())) Emit(sink.Api,combo.Select(Declared).ToArray(),where);
            }
            foreach(var call in s.Calls) {
                var bound=call.Args.Select(a=>Bind(a,args)).ToArray();
                if(args==null) bound=bound.Select(Declared).ToArray();
                if(args==null && bound.All(b=>b is Null || b is Int)) continue;
                string where=args==null || !call.Args.Any(HasParam)?SiteOf(h):origin;
                Resolve(call.Target,bound,seen,depth+1,where);
            }
        }
        string emitting;
        void Emit(string api,Val[] a,string site) {
            emitting=site;
            if(skip.Contains(site)) { scan.Skipped.Add(site); return; }
            // The check itself looks up whatever a row names.
            if(site.StartsWith("ClientBindings.",StringComparison.Ordinal) || site.StartsWith("ClientChecks",StringComparison.Ordinal) || site.StartsWith("GameTypes.",StringComparison.Ordinal)) return;
            if(api=="Type") {
                if(a.Length>0 && a[0] is Ty named) { if(!Add("T",named.Assembly,named.Type,"","")) scan.Unresolved.Add(site+"\tType\t"+named.Type+" (not on this type)"); }
                return;
            }
            if(api=="Patch") {
                var original=a.Length>0?a[0]:Unknown.Instance;
                if(original is Member m && m.Kind=="M" && m.Args.Length>=2 && m.Args[0] is Ty owner && m.Args[1] is Str targetName && MayBeClient(owner.Assembly,owner.Type)) {
                    string targetSignature=m.Args.Length<=2 || m.Args[2] is Null?"*":Parameters(m.Args[2]);
                    if((targetSignature!="*" || m.Args.Length<=2 || m.Args[2] is Null) && client.NoBody(owner.Type,targetName.Value,targetSignature))
                        scan.BodyFailures.Add(site+": "+owner.Type+"."+targetName.Value+" "+targetSignature+" has no body; patch the concrete override instead");
                }
                if(!(original is Member) && !(original is Null) && !(original is Result)) scan.Unresolved.Add(site+"\tPatch\t(target not known from the IL)");
                return;
            }
            Val type=a.Length>0?a[0]:Unknown.Instance;
            if(api=="MoveNext") {
                if(type is Member g && g.Args.Length>1 && g.Args[0] is Ty gt && g.Args[1] is Str gn) {
                    // The scan reads both arms of if(row.Iterator). The client DLLs say which rows really are iterators: the rest are plain targets, patched as they are.
                    string shape=Parameters(g.Args.Length>2?g.Args[2]:null);
                    if(!Add("E",gt.Assembly,gt.Type,gn.Value,shape) && !Add("M",gt.Assembly,gt.Type,gn.Value,shape)) scan.Unresolved.Add(site+"\tMoveNext\t"+gt.Type+"."+gn.Value+" (not on this type)");
                }
                else scan.Unresolved.Add(site+"\tMoveNext\t(unknown iterator)");
                return;
            }
            if(type is Member || type is Null) return;
            var t=type as Ty;
            if(t==null) { scan.Unresolved.Add(site+"\t"+api+"\t(unknown type)"); return; }
            if(!MayBeClient(t.Assembly,t.Type)) return;
            string kind=api.StartsWith("Field",StringComparison.Ordinal)?"F":api.StartsWith("Property",StringComparison.Ordinal)?"P":api.StartsWith("Ctor",StringComparison.Ordinal)?"C":"M";
            if(api=="Enumerate") { scan.Unresolved.Add(site+"\tEnumerate\t"+t.Type+".(members chosen at run time)"); return; }
            string name=kind=="C"?".ctor":(a.Length>1?(a[1] as Str)?.Value:null);
            if(name==null) { scan.Unresolved.Add(site+"\t"+api+"\t"+t.Type+".(unknown member)"); return; }
            int at=kind=="C"?1:2;
            string signature=(kind=="M" || kind=="C") && a.Length>at?Parameters(a[at]):"*";
            // A guess from a static type, or a try-this-then-that helper. Not a row until someone says what it really reaches.
            if(!Add(kind,t.Assembly,t.Type,name,signature)) scan.Unresolved.Add(site+"\t"+api+"\t"+t.Type+"."+name+" (not on this type)");
        }
        // False: the client DLLs here say it does not exist.
        bool Add(string kind,string assembly,string type,string name,string signature) {
            if(!MayBeClient(assembly,type)) return true;
            string where=assembly??assemblyOf(type);
            if(where==null) { string only=Row(kind,null,type,name,signature); scan.Rows.Add(only); scan.RuntimeOnly.Add(only); scan.From(only,emitting); return true; }
            string row=Row(kind,where,type,name,signature);
            if(client.Problem(row)!=null) return false;
            scan.Rows.Add(row); scan.From(row,emitting);
            return true;
        }
        static string Parameters(Val parameters) {
            if(parameters is Arr arr && !arr.Open && arr.Items.Values.All(v=>v is Ty)) return "("+string.Join(",",arr.Items.Values.Select(v=>((Ty)v).Type))+")";
            return "*"; // Any overload of that name: AccessTools with no list, or a list only known at run time.
        }
        // Called by other plugin code: its parameters are bound at those calls. A method nothing calls (a Harmony patch) is its own root.
        bool Helper(MethodDefinitionHandle h) { if(called==null) called=new HashSet<MethodDefinitionHandle>(summaries.Values.SelectMany(s=>s.Calls).Select(c=>c.Target)); return called.Contains(h); }
        HashSet<MethodDefinitionHandle> called;
        static bool HasParam(Val v) => v is Result r && r.Args.Any(HasParam) || v is Param || v is Arr a && a.Items.Values.Any(HasParam) || v is Member m && m.Args.Any(HasParam) || v is Each e && HasParam(e.Items) || v is Tuple t && t.Items.Any(HasParam) || v is FieldType f && HasParam(f.Field);
        // A name no assembly here holds counts as the client's, unless it is the plugin's own or a runtime namespace.
        bool MayBeClient(string assembly,string type) {
            string where=assembly??assemblyOf(type);
            if(where!=null) return where!="$plugin" && IsClientAssembly(where);
            if(type==null || IsOwn(type)) return false;
            return !new[]{"System.","Microsoft.","Mono.","BepInEx.","HarmonyLib.","MonoMod.","SabberStoneCore."}.Any(p=>type.StartsWith(p,StringComparison.Ordinal));
        }
        HashSet<string> own;
        bool IsOwn(string type) { if(own==null) own=new HashSet<string>(md.TypeDefinitions.Select(h=>TypeName(md,h)),StringComparer.Ordinal); return own.Contains(type); }
        string SiteOf(MethodDefinitionHandle h) {
            var m=md.GetMethodDefinition(h);
            return TypeName(md,m.GetDeclaringType())+"."+md.GetString(m.Name);
        }
        (string type,string assembly) Static(EntityHandle h) {
            switch(h.Kind) {
                case HandleKind.TypeReference: var r=(TypeReferenceHandle)h; return (TypeName(md,r),ScopeOf(md,r));
                case HandleKind.TypeDefinition: return (TypeName(md,(TypeDefinitionHandle)h),"$plugin");
                case HandleKind.TypeSpecification:
                    var reader=md.GetBlobReader(md.GetTypeSpecification((TypeSpecificationHandle)h).Signature);
                    if(reader.ReadSignatureTypeCode()==SignatureTypeCode.GenericTypeInstance) { reader.ReadCompressedInteger(); return Static(reader.ReadTypeHandle()); }
                    return (null,null);
                default: return (null,null);
            }
        }
        static Dictionary<int,OpCode> ops;
        static OpCode Op(int value) {
            if(ops==null) ops=typeof(OpCodes).GetFields(BindingFlags.Public|BindingFlags.Static).Select(f=>(OpCode)f.GetValue(null)).ToDictionary(o=>(int)(ushort)o.Value);
            return ops[value];
        }
        static int Pops(StackBehaviour b) {
            switch(b) {
                case StackBehaviour.Pop0: return 0;
                case StackBehaviour.Pop1: case StackBehaviour.Popi: case StackBehaviour.Popref: return 1;
                case StackBehaviour.Pop1_pop1: case StackBehaviour.Popi_pop1: case StackBehaviour.Popi_popi: case StackBehaviour.Popi_popi8: case StackBehaviour.Popi_popr4: case StackBehaviour.Popi_popr8: case StackBehaviour.Popref_pop1: case StackBehaviour.Popref_popi: return 2;
                case StackBehaviour.Popi_popi_popi: case StackBehaviour.Popref_popi_popi: case StackBehaviour.Popref_popi_popi8: case StackBehaviour.Popref_popi_popr4: case StackBehaviour.Popref_popi_popr8: case StackBehaviour.Popref_popi_popref: return 3;
                default: return 0;
            }
        }
        static int Pushes(StackBehaviour b) {
            switch(b) {
                case StackBehaviour.Push0: return 0;
                case StackBehaviour.Push1: case StackBehaviour.Pushi: case StackBehaviour.Pushi8: case StackBehaviour.Pushr4: case StackBehaviour.Pushr8: case StackBehaviour.Pushref: return 1;
                case StackBehaviour.Push1_push1: return 2;
                default: return 0;
            }
        }
        Summary Walk(MethodDefinitionHandle h) {
            var summary=new Summary();
            var def=md.GetMethodDefinition(h);
            if(def.RelativeVirtualAddress==0) return summary;
            var body=pe.GetMethodBody(def.RelativeVirtualAddress);
            bool instance=(def.Attributes&MethodAttributes.Static)==0;
            var sig=def.DecodeSignature(Signatures,null);
            var parameterTypes=sig.ParameterTypes.ToArray();
            var locals=new Dictionary<int,Val>();
            string[] localTypes=new string[0];
            if(!body.LocalSignature.IsNil) localTypes=md.GetStandaloneSignature(body.LocalSignature).DecodeLocalSignature(Signatures,null).ToArray();
            var stack=new List<Val>();
            Func<Val> pop=()=>{ if(stack.Count==0) return Unknown.Instance; var top=stack[stack.Count-1]; stack.RemoveAt(stack.Count-1); return top; };
            Action<Val> push=stack.Add;
            string site=SiteOf(h);
