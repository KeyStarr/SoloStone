    static string RefRow(MetadataReader md,MemberReferenceHandle handle) {
        var member=md.GetMemberReference(handle);
        TypeReferenceHandle parent=default(TypeReferenceHandle);
        if(member.Parent.Kind==HandleKind.TypeReference) parent=(TypeReferenceHandle)member.Parent;
        else if(member.Parent.Kind==HandleKind.TypeSpecification) {
            var reader=md.GetBlobReader(md.GetTypeSpecification((TypeSpecificationHandle)member.Parent).Signature);
            if(reader.ReadSignatureTypeCode()==SignatureTypeCode.GenericTypeInstance) { reader.ReadCompressedInteger(); var inner=reader.ReadTypeHandle(); if(inner.Kind==HandleKind.TypeReference) parent=(TypeReferenceHandle)inner; }
        }
        if(parent.IsNil) return null;
        string scope=ScopeOf(md,parent);
        if(!IsClientAssembly(scope)) return null;
        string name=md.GetString(member.Name), type=TypeName(md,parent);
        var peek=md.GetBlobReader(member.Signature);
        if(peek.ReadSignatureHeader().Kind==SignatureKind.Field) return Row("F",scope,type,name,member.DecodeFieldSignature(Signatures,null));
        var method=member.DecodeMethodSignature(Signatures,null);
        return Row(name==".ctor"?"C":"M",scope,type,name,method.ReturnType+"("+string.Join(",",method.ParameterTypes)+")");
    }

