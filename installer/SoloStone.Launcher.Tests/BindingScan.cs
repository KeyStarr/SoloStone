                stopped=false;
                int first=il.ReadByte();
                var op=Op(first==0xFE?0xFE00|il.ReadByte():first);
                int operand=0; long big=0;
                switch(op.OperandType) {
                    case OperandType.InlineNone: break;
                    case OperandType.ShortInlineBrTarget: case OperandType.ShortInlineI: case OperandType.ShortInlineVar: operand=il.ReadByte(); break;
                    case OperandType.InlineVar: operand=il.ReadUInt16(); break;
                    case OperandType.InlineI8: case OperandType.InlineR: big=il.ReadInt64(); break;
                    case OperandType.InlineSwitch: { int n=il.ReadInt32(); for(int i=0;i<n;i++) il.ReadInt32(); break; }
                    default: operand=il.ReadInt32(); break;
                }
                string name=op.Name;
                if(op.FlowControl==FlowControl.Branch || op.FlowControl==FlowControl.Cond_Branch) {
                    bool shortForm=op.OperandType==OperandType.ShortInlineBrTarget;
                    if(op.OperandType==OperandType.ShortInlineBrTarget || op.OperandType==OperandType.InlineBrTarget) {
                        for(int i=0,n=Pops(op.StackBehaviourPop);i<n;i++) pop();
                        int target=il.Offset+(shortForm?(sbyte)operand:operand);
                        if(!atBranch.ContainsKey(target)) atBranch[target]=new List<Val>(stack);
                        if(op.FlowControl==FlowControl.Branch) stopped=true;
                        continue;
                    }
                }
                if(op.FlowControl==FlowControl.Throw) { stack.Clear(); stopped=true; continue; }
                if(name=="ldstr") { push(new Str { Value=md.GetUserString(MetadataTokens.UserStringHandle(operand&0xFFFFFF)) }); continue; }
                if(name=="ldnull") { push(new Null()); continue; }
                if(name.StartsWith("ldc.i4",StringComparison.Ordinal)) {
