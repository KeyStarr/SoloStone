                    case "GetMethods": case "GetFields": case "GetProperties": case "GetMembers": case "GetNestedTypes": case "GetEvent": case "GetEvents": case "GetMember":
                        summary.Sinks.Add(new Sink { Api="Enumerate", Args=receiver }); result(Unknown.Instance); return;
                }
            }
            if(opcode=="newobj") { result(new Obj { Type=type, Assembly=assembly }); return; }
            result(TypedObj(decoded.ReturnType));
        }
