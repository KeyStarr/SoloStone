    public static Live Reach(PEReader pe,MetadataReader md) {
        var methodsNamed=new Dictionary<string,List<MethodDefinitionHandle>>(StringComparer.Ordinal); var typesNamed=new Dictionary<string,TypeDefinitionHandle>(StringComparer.Ordinal);
        foreach(var t in md.TypeDefinitions) typesNamed[TypeName(md,t)]=t;
        foreach(var m in md.MethodDefinitions) { string name=md.GetString(md.GetMethodDefinition(m).Name); if(!methodsNamed.TryGetValue(name,out var list)) methodsNamed[name]=list=new List<MethodDefinitionHandle>(); list.Add(m); }
        var live=new Live(); var touched=new HashSet<TypeDefinitionHandle>(); var work=new Stack<MethodDefinitionHandle>();
        Action<MethodDefinitionHandle> run=null; Action<TypeDefinitionHandle> touch=null; Action<EntityHandle> use=null;
        Action<string> typesIn=text=>{ foreach(string part in text.Split(new[]{'<','>',',','[',']','&','*',' '},StringSplitOptions.RemoveEmptyEntries)) if(typesNamed.TryGetValue(part,out var named)) touch(named); };
        run=h=>{ if(live.Methods.Add(h)) { work.Push(h); touch(md.GetMethodDefinition(h).GetDeclaringType()); } };
        touch=t=>{
            if(!touched.Add(t)) return;
            var def=md.GetTypeDefinition(t);
            if(!def.BaseType.IsNil) use(def.BaseType);
            foreach(var h in def.GetMethods()) { var m=md.GetMethodDefinition(h); string name=md.GetString(m.Name); if(name==".cctor" || (m.Attributes&MethodAttributes.Virtual)!=0 || UnityMessages.Contains(name) || (name==".ctor" && m.GetParameters().Count==0) || IsPublicAccessor(m,name) || (name.StartsWith("ShouldSerialize",StringComparison.Ordinal) && (m.Attributes&MethodAttributes.Public)==MethodAttributes.Public)) run(h); }
        };
        use=h=>{
            switch(h.Kind) {
                case HandleKind.MethodDefinition: run((MethodDefinitionHandle)h); break;
                case HandleKind.FieldDefinition: touch(md.GetFieldDefinition((FieldDefinitionHandle)h).GetDeclaringType()); break;
                case HandleKind.TypeDefinition: touch((TypeDefinitionHandle)h); break;
                case HandleKind.TypeSpecification: typesIn(md.GetTypeSpecification((TypeSpecificationHandle)h).DecodeSignature(Signatures,null)); break;
                case HandleKind.MethodSpecification: { var spec=md.GetMethodSpecification((MethodSpecificationHandle)h); use(spec.Method); foreach(string argument in spec.DecodeSignature(Signatures,null)) typesIn(argument); break; }
                case HandleKind.MemberReference: {
                    var handle=(MemberReferenceHandle)h; live.Refs.Add(handle);
                    var member=md.GetMemberReference(handle); use(member.Parent);
                    // A member of a generic plugin class is a reference with the class as its parent, so it has no direct method token.
                    if(member.Parent.Kind==HandleKind.TypeSpecification || member.Parent.Kind==HandleKind.TypeDefinition) {
                        string owner=member.Parent.Kind==HandleKind.TypeDefinition?TypeName(md,(TypeDefinitionHandle)member.Parent):md.GetTypeSpecification((TypeSpecificationHandle)member.Parent).DecodeSignature(Signatures,null);
                        int open=owner.IndexOf('<'); if(open>=0) owner=owner.Substring(0,open);
                        if(typesNamed.TryGetValue(owner,out var type)) foreach(var candidate in md.GetTypeDefinition(type).GetMethods()) if(md.GetString(md.GetMethodDefinition(candidate).Name)==md.GetString(member.Name)) run(candidate);
                    }
                    break;
                }
            }
        };
        foreach(var t in md.TypeDefinitions) {
            var def=md.GetTypeDefinition(t);
            if(def.BaseType.Kind==HandleKind.TypeReference && TypeName(md,(TypeReferenceHandle)def.BaseType)==PluginBase) { touch(t); foreach(var h in def.GetMethods()) run(h); }
        }
        if(live.Methods.Count==0) return null;
        if(typesNamed.TryGetValue("<Module>",out var module)) touch(module);
        // Not in any method's body: an attribute's constructor, and the interface method an explicit implementation names.
        foreach(var a in md.CustomAttributes) { var ctor=md.GetCustomAttribute(a).Constructor; if(ctor.Kind==HandleKind.MemberReference) live.Refs.Add((MemberReferenceHandle)ctor); }
        foreach(var t in md.TypeDefinitions) foreach(var i in md.GetTypeDefinition(t).GetMethodImplementations()) { var declared=md.GetMethodImplementation(i).MethodDeclaration; if(declared.Kind==HandleKind.MemberReference) live.Refs.Add((MemberReferenceHandle)declared); }
        // A string names a method only on a type this body has a token for, on its own class, or on a type a helper it calls has a token for: new HarmonyMethod(typeof(X), nameof(Y)),
        // nameof(Y) beside its own Y, or Patch(nameof(X.Y)) with the typeof(X) inside Patch. Any wider and every string "Initialize" a client lookup uses would keep alive every plugin method called Initialize.
        var tokensOf=new Dictionary<MethodDefinitionHandle,HashSet<TypeDefinitionHandle>>();
        Func<MethodDefinitionHandle,HashSet<TypeDefinitionHandle>> tokensIn=h=>{
            if(tokensOf.TryGetValue(h,out var known)) return known;
            var found=new HashSet<TypeDefinitionHandle>();
            Operands(pe,md,md.GetMethodDefinition(h),t=>{ if(t.Kind==HandleKind.TypeDefinition) found.Add((TypeDefinitionHandle)t); },text=>{});
            return tokensOf[h]=found;
        };
        while(work.Count>0) {
            var handle=work.Pop(); var body=md.GetMethodDefinition(handle); var strings=new List<string>(); var scope=new HashSet<TypeDefinitionHandle>();
            for(var own=body.GetDeclaringType();!own.IsNil;own=md.GetTypeDefinition(own).GetDeclaringType()) scope.Add(own);
            Operands(pe,md,body,h=>{ use(h); if(h.Kind==HandleKind.TypeDefinition) scope.Add((TypeDefinitionHandle)h); else if(h.Kind==HandleKind.MethodDefinition) scope.UnionWith(tokensIn((MethodDefinitionHandle)h)); },strings.Add,f=>live.FieldsRead.Add(f));
            live.Strings.UnionWith(strings);
            if(MethodName(md,handle)!=ShopTable) live.Named.UnionWith(strings);
            foreach(string text in strings) {
                if(methodsNamed.TryGetValue(text,out var named)) foreach(var h in named) if(scope.Contains(md.GetMethodDefinition(h).GetDeclaringType())) run(h);
                // A name built by concatenation: Hook("VoidFinalizer" + count).
                if(text.Length>=4) foreach(var type in scope.ToArray()) foreach(var h in md.GetTypeDefinition(type).GetMethods()) if(md.GetString(md.GetMethodDefinition(h).Name).StartsWith(text,StringComparison.Ordinal)) run(h);
            }
        }
        // A lookup's static field nothing reads: its row would block a player over a value nothing uses. A read inside a static constructor counts, so a chain falls one wrap at a time.
        foreach(var t in touched) foreach(var f in md.GetTypeDefinition(t).GetFields()) {
            var field=md.GetFieldDefinition(f);
            if((field.Attributes&FieldAttributes.Static)==0 || !LookupTypes.Contains(field.DecodeSignature(Signatures,null)) || live.FieldsRead.Contains(f)) continue;
            live.UnreadLookups.Add(TypeName(md,t)+"."+md.GetString(field.Name));
        }
        return live;
    }
    const string ShopTable="NativeShop..cctor";
    static readonly HashSet<string> LookupTypes=new HashSet<string>(StringComparer.Ordinal){"System.Reflection.FieldInfo","System.Reflection.PropertyInfo","System.Reflection.MethodInfo","System.Reflection.MethodBase","System.Reflection.ConstructorInfo","System.Reflection.MemberInfo","System.Type"};
    static string MethodName(MetadataReader md,MethodDefinitionHandle h) { var m=md.GetMethodDefinition(h); return TypeName(md,m.GetDeclaringType())+"."+md.GetString(m.Name); }

    // ---- The client's DLLs, read as metadata, so a row that names nothing fails at build time.
    public sealed class Client
    {
        readonly List<(string assembly,PEReader pe,MetadataReader md)> modules=new List<(string,PEReader,MetadataReader)>();
        readonly Dictionary<string,(string assembly,MetadataReader md,TypeDefinitionHandle def)> types=new Dictionary<string,(string,MetadataReader,TypeDefinitionHandle)>(StringComparer.Ordinal);
        public Client(IEnumerable<string> folders) {
            foreach(string folder in folders.Where(Directory.Exists))
                foreach(string dll in Directory.GetFiles(folder,"*.dll").OrderBy(p=>p,StringComparer.Ordinal)) {
                    PEReader pe=null;
                    try {
                        pe=new PEReader(File.OpenRead(dll)); var md=pe.GetMetadataReader();
                        string name=Path.GetFileNameWithoutExtension(dll); modules.Add((name,pe,md));
                        foreach(var h in md.TypeDefinitions) { string full=TypeName(md,h); if(!types.ContainsKey(full)) types[full]=(name,md,h); }
                    } catch(BadImageFormatException) { pe?.Dispose(); } catch(InvalidOperationException) { pe?.Dispose(); }
                }
        }
        public string AssemblyOf(string type) { if(type==null) return null; int at=type.IndexOf('<'); string open=at<0?type:type.Substring(0,at); return types.TryGetValue(open,out var found)?found.assembly:null; }
        // The declared type of a field or property, for AccessTools.Field(other.FieldType, name).
        public string MemberType(string type,string member) {
            int at=type.IndexOf('<'); if(at>=0) type=type.Substring(0,at);
            for(int depth=0;depth<32 && types.TryGetValue(type,out var found);depth++) {
                var def=found.md.GetTypeDefinition(found.def);
                foreach(var h in def.GetFields()) { var f=found.md.GetFieldDefinition(h); if(found.md.GetString(f.Name)==member) return Open(f.DecodeSignature(Signatures,null)); }
                foreach(var h in def.GetProperties()) { var p=found.md.GetPropertyDefinition(h); if(found.md.GetString(p.Name)==member) return Open(p.DecodeSignature(Signatures,null).ReturnType); }
                type=BaseName(found.md,def); if(type==null) return null;
            }
            return null;
        }
        static string Open(string name) { int at=name.IndexOf('<'); return at<0?name:name.Substring(0,at); }
        public bool NoBody(string type,string member,string signature) {
            for(int depth=0;depth<32 && types.TryGetValue(type,out var found);depth++) {
                var def=found.md.GetTypeDefinition(found.def);
                var methods=def.GetMethods().Select(h=>found.md.GetMethodDefinition(h)).Where(m=>found.md.GetString(m.Name)==member && (signature=="*" || "("+string.Join(",",m.DecodeSignature(Signatures,null).ParameterTypes)+")"==signature)).ToArray();
                if(methods.Length>0) return methods.All(m=>m.RelativeVirtualAddress==0);
                type=BaseName(found.md,def);
                if(type==null) break;
            }
            return false;
        }
        public bool HasAssembly(string name) => modules.Any(m=>string.Equals(m.assembly,name,StringComparison.OrdinalIgnoreCase));
        // Null: present. Otherwise why not. Mirrors ClientBindings.Missing.
        public string Problem(string row) {
            string[] p=row.Split('\t');
            string kind=p[0], assembly=p[1], type=p[2], member=p[3], signature=p[4];
            if(kind=="A") return HasAssembly(assembly)?null:"assembly not in references: "+assembly;
            if(!types.TryGetValue(type,out var found)) return "type not found: "+type;
            if(kind=="T") return null;
            for(int depth=0;depth<32;depth++) {
                var def=found.md.GetTypeDefinition(found.def);
                if(Declares(found.md,def,kind,member,signature)) return null;
                string next=BaseName(found.md,def);
                if(next==null || !types.TryGetValue(next,out found)) {
                    // The chain left the client DLLs for the core library, which references/game does not hold. This runtime's copy answers for object, Enum, Exception and the like.
                    for(var core=next==null?null:Type.GetType(next,false);core!=null;core=core.BaseType)
                        if(core.GetMember(member,BindingFlags.Public|BindingFlags.NonPublic|BindingFlags.Instance|BindingFlags.Static|BindingFlags.DeclaredOnly).Length!=0) return null;
                    break;
                }
            }
            return "member not found: "+type+"."+member+" "+signature;
        }
        static string BaseName(MetadataReader md,TypeDefinition def) {
            var b=def.BaseType;
            if(b.IsNil) return null;
            if(b.Kind==HandleKind.TypeDefinition) return TypeName(md,(TypeDefinitionHandle)b);
            if(b.Kind==HandleKind.TypeReference) return TypeName(md,(TypeReferenceHandle)b);
            if(b.Kind==HandleKind.TypeSpecification) {
                var reader=md.GetBlobReader(md.GetTypeSpecification((TypeSpecificationHandle)b).Signature);
                if(reader.ReadSignatureTypeCode()!=SignatureTypeCode.GenericTypeInstance) return null;
                reader.ReadCompressedInteger(); var inner=reader.ReadTypeHandle();
                return inner.Kind==HandleKind.TypeDefinition?TypeName(md,(TypeDefinitionHandle)inner):inner.Kind==HandleKind.TypeReference?TypeName(md,(TypeReferenceHandle)inner):null;
            }
            return null;
        }
        // AccessTools.EnumeratorMoveNext: the first newobj in the method must make a type with a MoveNext. An existing method is not enough: a transpiler on it needs that MoveNext.
        bool IsIterator(MetadataReader md,MethodDefinition method) {
            if(method.RelativeVirtualAddress==0) return false;
            var il=modules.First(m=>m.md==md).pe.GetMethodBody(method.RelativeVirtualAddress).GetILReader();
            while(il.RemainingBytes>0) {
                int first=il.ReadByte();
                var op=OpOf(first==0xFE?0xFE00|il.ReadByte():first);
                if(op==OpCodes.Newobj) {
                    var made=(EntityHandle)MetadataTokens.Handle(il.ReadInt32());
                    // A method in a generic class makes its iterator through a type specification.
                    TypeDefinitionHandle owner=default(TypeDefinitionHandle);
                    if(made.Kind==HandleKind.MethodDefinition) owner=md.GetMethodDefinition((MethodDefinitionHandle)made).GetDeclaringType();
                    else if(made.Kind==HandleKind.MemberReference) {
                        var parent=md.GetMemberReference((MemberReferenceHandle)made).Parent;
                        if(parent.Kind==HandleKind.TypeDefinition) owner=(TypeDefinitionHandle)parent;
                        else if(parent.Kind==HandleKind.TypeSpecification) {
                            var reader=md.GetBlobReader(md.GetTypeSpecification((TypeSpecificationHandle)parent).Signature);
                            if(reader.ReadSignatureTypeCode()==SignatureTypeCode.GenericTypeInstance) { reader.ReadCompressedInteger(); var inner=reader.ReadTypeHandle(); if(inner.Kind==HandleKind.TypeDefinition) owner=(TypeDefinitionHandle)inner; }
                        }
                    }
                    if(owner.IsNil) return false;
                    return md.GetTypeDefinition(owner).GetMethods().Any(h=>md.GetString(md.GetMethodDefinition(h).Name)=="MoveNext");
                }
                switch(op.OperandType) {
                    case OperandType.InlineNone: break;
                    case OperandType.ShortInlineBrTarget: case OperandType.ShortInlineI: case OperandType.ShortInlineVar: il.ReadByte(); break;
                    case OperandType.InlineVar: il.ReadUInt16(); break;
                    case OperandType.InlineI8: case OperandType.InlineR: il.ReadInt64(); break;
                    case OperandType.InlineSwitch: { int n=il.ReadInt32(); for(int i=0;i<n;i++) il.ReadInt32(); break; }
                    case OperandType.ShortInlineR: il.ReadSingle(); break;
                    default: il.ReadInt32(); break;
                }
            }
            return false;
        }
        static Dictionary<int,OpCode> opTable;
        public static OpCode OpOf(int value) {
            if(opTable==null) opTable=typeof(OpCodes).GetFields(BindingFlags.Public|BindingFlags.Static).Select(f=>(OpCode)f.GetValue(null)).ToDictionary(o=>(int)(ushort)o.Value);
            return opTable[value];
        }
        bool Declares(MetadataReader md,TypeDefinition def,string kind,string member,string signature) {
            if(kind=="F") { foreach(var h in def.GetFields()) { var f=md.GetFieldDefinition(h); if(md.GetString(f.Name)==member && (signature=="*" || f.DecodeSignature(Signatures,null)==signature)) return true; } return false; }
            if(kind=="P") { foreach(var h in def.GetProperties()) if(md.GetString(md.GetPropertyDefinition(h).Name)==member) return true; return false; }
            foreach(var h in def.GetMethods()) {
                var m=md.GetMethodDefinition(h);
                if(md.GetString(m.Name)!=member) continue;
                var s=m.DecodeSignature(Signatures,null);
                string parameters="("+string.Join(",",s.ParameterTypes)+")";
                if(signature!="*" && signature!=parameters && signature!=s.ReturnType+parameters) continue;
                if(kind!="E" || IsIterator(md,m)) return true;
            }
            return false;
        }
    }

    public static Scan Read(string dll,Client client,HashSet<string> skip=null) {
        var scan=new Scan();
        using(var pe=new PEReader(File.OpenRead(dll))) {
            var md=pe.GetMetadataReader();
            Compiled(md,scan);
            new Interpreter(pe,md,scan,client,skip??new HashSet<string>(StringComparer.Ordinal)).Run();
            var live=Reach(pe,md);
            if(live!=null) {
                var reached=new Scan();
                Compiled(md,reached,live.Refs);
                new Interpreter(pe,md,reached,client,skip??new HashSet<string>(StringComparer.Ordinal)).Run(live.Methods,live.Named);
                scan.LiveNames=live.Named; scan.UnreadLookups=live.UnreadLookups;
                scan.LiveRows=reached.Rows;
                scan.DeadSites=new SortedSet<string>(scan.Unresolved.Except(reached.Unresolved),StringComparer.Ordinal);
                scan.DeadMethods=new SortedSet<string>(StringComparer.Ordinal);
                scan.LiveMethods=new SortedSet<string>(live.Methods.Select(h=>MethodName(md,h)),StringComparer.Ordinal);
                foreach(var h in md.MethodDefinitions.Where(h=>!live.Methods.Contains(h))) {
                    var def=md.GetMethodDefinition(h); string name=MethodName(md,h);
                    // A string in live code names this method's name, on a class the narrow rule does not link. Worth a look before calling it dead.
                    scan.DeadMethods.Add(name+(live.Strings.Contains(md.GetString(def.Name))?"  (a live string has this name)":""));
                    Operands(pe,md,def,token=>{
                        if(token.Kind==HandleKind.MethodSpecification) token=md.GetMethodSpecification((MethodSpecificationHandle)token).Method;
                        if(token.Kind!=HandleKind.MemberReference) return;
                        string row=RefRow(md,(MemberReferenceHandle)token); if(row!=null) scan.From(row,name);
                    },text=>{});
                }
            }
        }
        return scan;
    }
    // plugin/client-bindings.extra.txt. "row <kind> <type> <member> <signature> # why": a target a site reaches that the IL does not show.
    // "site <site> # why": an unresolved site, written as the scan prints it, that its rows above cover. A stale line fails, so the list cannot rot.
    // "skip <Class.Method> # why": this code tolerates a missing target, a diagnostic or cosmetic read, so a retail patch must not block every player over it. No rows come from it.
    public sealed class Extra { public List<string> Rows=new List<string>(); public HashSet<string> Sites=new HashSet<string>(StringComparer.Ordinal); public HashSet<string> Skips=new HashSet<string>(StringComparer.Ordinal); public List<string> Problems=new List<string>(); }
    public static Extra ReadExtra(string file,Client client) {
        var extra=new Extra();
        if(!File.Exists(file)) return extra;
        foreach(string raw in File.ReadAllLines(file)) {
            string line=raw.Trim();
            if(line.Length==0 || line[0]=='#') continue;
            int hash=line.IndexOf(" # ",StringComparison.Ordinal);
            if(hash<0) { extra.Problems.Add("extra line without a reason: "+line); continue; }
            string body=line.Substring(0,hash).Trim();
            if(body.StartsWith("site ",StringComparison.Ordinal)) extra.Sites.Add(body.Substring(5).Replace(" | ","\t"));
            else if(body.StartsWith("skip ",StringComparison.Ordinal)) extra.Skips.Add(body.Substring(5).Trim());
            else if(body.StartsWith("row ",StringComparison.Ordinal)) {
                string[] p=body.Substring(4).Split(new[]{' '},4,StringSplitOptions.RemoveEmptyEntries);
                if(p.Length<3) { extra.Problems.Add("bad extra row: "+line); continue; }
                extra.Rows.Add(Row(p[0],client.AssemblyOf(p[1]),p[1],p[2],p.Length>3?p[3]:"*"));
            }
            else extra.Problems.Add("bad extra line: "+line);
        }
        return extra;
    }
    public sealed class Outcome { public SortedSet<string> Rows; public List<string> Failures=new List<string>(); public SortedSet<string> DeadMethods=new SortedSet<string>(StringComparer.Ordinal); public SortedSet<string> LiveMethods=new SortedSet<string>(StringComparer.Ordinal); public SortedDictionary<string,string> DeadRows=new SortedDictionary<string,string>(StringComparer.Ordinal); }
    // plugins: every build V1 runs in. A row one build lacks is still required: all targets are required in v0.1.
    public static Outcome Build(IEnumerable<string> plugins,Client client,string extraFile) {
        var extra=ReadExtra(extraFile,client);
        var outcome=new Outcome { Rows=new SortedSet<string>(extra.Rows,StringComparer.Ordinal) };
        outcome.Failures.AddRange(extra.Problems);
        var unresolved=new SortedSet<string>(StringComparer.Ordinal); var runtimeOnly=new HashSet<string>(StringComparer.Ordinal);
        var skipped=new HashSet<string>(StringComparer.Ordinal);
        var deadRows=new SortedSet<string>(StringComparer.Ordinal); var liveRows=new HashSet<string>(StringComparer.Ordinal); var deadSites=new SortedSet<string>(StringComparer.Ordinal);
        var sources=new Dictionary<string,SortedSet<string>>(StringComparer.Ordinal); HashSet<string> names=null; var unreadLookups=new SortedSet<string>(StringComparer.Ordinal);
        foreach(string plugin in plugins) {
            var scan=Read(plugin,client,extra.Skips);
            foreach(var source in scan.Sources) { if(!sources.TryGetValue(source.Key,out var known)) sources[source.Key]=known=new SortedSet<string>(StringComparer.Ordinal); known.UnionWith(source.Value); }
            if(scan.LiveRows!=null) { names=names??new HashSet<string>(StringComparer.Ordinal); names.UnionWith(scan.LiveNames); unreadLookups.UnionWith(scan.UnreadLookups); deadRows.UnionWith(scan.Rows); liveRows.UnionWith(scan.LiveRows); deadSites.UnionWith(scan.DeadSites); outcome.DeadMethods.UnionWith(scan.DeadMethods); outcome.LiveMethods.UnionWith(scan.LiveMethods); }
            outcome.Failures.AddRange(scan.BodyFailures.Where(f=>!outcome.Failures.Contains(f))); outcome.Rows.UnionWith(scan.Rows); unresolved.UnionWith(scan.Unresolved); runtimeOnly.UnionWith(scan.RuntimeOnly); skipped.UnionWith(scan.Skipped); }
        const string DeadFix="; compile that code out of a public build or delete it (tool bindings --list-dead names the dead methods): ";
        foreach(string row in deadRows.Where(r=>!liveRows.Contains(r) && !extra.Rows.Contains(r) && "MCFEP".IndexOf(r[0])>=0)) {
            string from=sources.TryGetValue(row,out var known)?string.Join(", ",known):"(not traced)";
            outcome.DeadRows[row]=from;
            outcome.Failures.Add("only code the plugin cannot reach binds this row, and V1 would block a player over it"+DeadFix+row.Replace('\t',' ')+" <- "+from);
        }
        foreach(string field in unreadLookups) outcome.Failures.Add("a lookup is held in a static field nothing reads, so its row would block a player over a value nothing uses; compile the field out of a public build or delete it: "+field);
        // A row in the extra file is a name the IL hides from the scan, but the name itself is still a string somewhere. If it isn't, the code that used it has gone.
        // A table can hold it inside a longer string ("Box.m_ArenaButton"), so this reads identifiers, and a name it finds by coincidence only keeps a row.
        var identifiers=names==null?null:new HashSet<string>(names.SelectMany(n=>System.Text.RegularExpressions.Regex.Split(n,@"[^\w`]+")),StringComparer.Ordinal);
        if(names!=null) foreach(string row in extra.Rows) { string[] p=row.Split('\t'); if(p[0]!="T" && p[3]!=".ctor" && !identifiers.Contains(p[3])) outcome.Failures.Add("plugin/client-bindings.extra.txt has a row no string in live code names, so V1 would block a player over it: "+row.Replace('\t',' ')); }
        foreach(string site in deadSites) outcome.Failures.Add("only code the plugin cannot reach has this binding site"+DeadFix+site.Replace("\t"," | "));
        foreach(string stale in extra.Skips.Where(s=>!skipped.Contains(s))) outcome.Failures.Add("stale skip in plugin/client-bindings.extra.txt: "+stale);
        foreach(string site in unresolved) if(!extra.Sites.Contains(site)) outcome.Failures.Add("binding site not covered, add it to plugin/client-bindings.extra.txt with what it reaches: "+site.Replace("\t"," | "));
        foreach(string stale in extra.Sites) if(!unresolved.Contains(stale)) outcome.Failures.Add("stale site in plugin/client-bindings.extra.txt: "+stale.Replace("\t"," | "));
        foreach(string row in outcome.Rows.Where(r=>!runtimeOnly.Contains(r))) { string problem=client.Problem(row); if(problem!=null) outcome.Failures.Add(problem+"   ("+row.Replace('\t',' ')+")"); }
        return outcome;
    }
    // tool bindings --references DIR --manifest FILE --extra FILE PLUGIN... [--write]
    // Check: the committed manifest must equal what these builds bind to. A target not covered fails here, and so does a stale row.
    public static int Run(string[] args) {
        bool write=args.Contains("--write"), list=args.Contains("--list-unresolved"), listDead=args.Contains("--list-dead");
        var rest=args.Where(a=>a!="--write" && a!="--list-unresolved" && a!="--list-dead").ToList();
        Func<string,string> take=name=>{ int at=rest.IndexOf(name); if(at<0 || at+1>=rest.Count) throw new InvalidOperationException("Usage: tool bindings --references DIR --manifest FILE --extra FILE PLUGIN... [--write]"); string value=rest[at+1]; rest.RemoveRange(at,2); return value; };
        string references=take("--references"), manifest=take("--manifest"), extra=take("--extra");
        if(rest.Count==0) throw new InvalidOperationException("Usage: tool bindings --references DIR --manifest FILE --extra FILE PLUGIN... [--write]");
        var client=new Client(new[]{Path.Combine(references,"game")});
        var outcome=Build(rest,client,extra);
        if(list) foreach(string failure in outcome.Failures) Console.WriteLine(failure);
        if(listDead) { foreach(string method in outcome.DeadMethods) Console.WriteLine("dead: "+method); foreach(string method in outcome.LiveMethods) Console.WriteLine("live: "+method); }
        if(outcome.Failures.Count!=0) { if(!list) foreach(string failure in outcome.Failures) Console.Error.WriteLine(failure); Console.Error.WriteLine("FAIL client bindings: "+outcome.Failures.Count+" problems"); return 1; }
        var lines=new[]{ManifestHeader}.Concat(outcome.Rows).ToArray();
        if(write) { File.WriteAllText(manifest,string.Join("\n",lines)+"\n"); Console.WriteLine("Wrote "+manifest+": "+outcome.Rows.Count+" rows"); return 0; }
        var committed=File.Exists(manifest)?File.ReadAllLines(manifest).Where(l=>l.Length!=0 && l[0]!='#').ToArray():new string[0];
        var missing=outcome.Rows.Except(committed,StringComparer.Ordinal).ToArray();
        var stale=committed.Except(outcome.Rows,StringComparer.Ordinal).ToArray();
        foreach(string row in missing) Console.Error.WriteLine("target not in the manifest: "+row.Replace('\t',' '));
        foreach(string row in stale) Console.Error.WriteLine("stale manifest row: "+row.Replace('\t',' '));
        if(missing.Length+stale.Length!=0) { Console.Error.WriteLine("FAIL client bindings: run `tool bindings ... --write` (installer/SoloStone.Launcher.Tests) and commit plugin/client-bindings.txt"); return 1; }
        Console.WriteLine("PASS client bindings: "+outcome.Rows.Count+" rows match "+rest.Count+" builds");
        return 0;
    }
