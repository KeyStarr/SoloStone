                if(name.StartsWith("ldarg",StringComparison.Ordinal) && !name.StartsWith("ldarga",StringComparison.Ordinal)) {
                    int index=name.Length>6 && name[5]=='.' && char.IsDigit(name[6])?name[6]-'0':operand;
                    if(instance && index==0) { var own=TypeName(md,def.GetDeclaringType()); push(new Obj { Type=own, Assembly="$plugin" }); continue; }
                    int slot=index-(instance?1:0);
                    push(new Param { Index=slot, Static=slot<parameterTypes.Length?parameterTypes[slot]:null }); continue;
                }
                if(name.StartsWith("stloc",StringComparison.Ordinal)) { int index=name.Length>6 && char.IsDigit(name[6])?name[6]-'0':operand; var stored=pop(); if(stored is Int) locals.Remove(index); else locals[index]=stored; /* A local int is a loop index, not the constant it starts at: a[i] must read every element. */ continue; }
                if(name.StartsWith("ldloc",StringComparison.Ordinal) && !name.StartsWith("ldloca",StringComparison.Ordinal)) {
                    int index=name.Length>6 && char.IsDigit(name[6])?name[6]-'0':operand;
                    if(locals.TryGetValue(index,out var known) && !(known is Unknown)) push(known);
                    else push(index<localTypes.Length?TypedObj(localTypes[index]):Unknown.Instance);
                    continue;
                }
                if(name=="dup") { var top=pop(); push(top); push(top); continue; }
                if(name=="ldtoken") {
                    var handle=(EntityHandle)MetadataTokens.Handle(operand);
                    if(handle.Kind==HandleKind.TypeReference || handle.Kind==HandleKind.TypeDefinition || handle.Kind==HandleKind.TypeSpecification) { var st=Static(handle); push(new Token { Type=st.type, Assembly=st.assembly }); }
                    else push(Unknown.Instance);
                    continue;
                }
                if(name=="newarr") { pop(); push(new Arr()); continue; }
                if(name.StartsWith("stelem",StringComparison.Ordinal)) {
                    var value=pop(); var index=pop(); var array=pop();
                    if(array is Arr a) { if(index is Int i) a.Items[i.Value]=value; else a.Open=true; }
                    continue;
                }
                if(name=="stsfld") {
                    var value=pop(); var handle=(EntityHandle)MetadataTokens.Handle(operand);
                    if(handle.Kind==HandleKind.FieldDefinition && md.GetString(def.Name)==".cctor") fields[(FieldDefinitionHandle)handle]=value;
                    continue;
                }
                if(name=="ldsfld") {
                    var handle=(EntityHandle)MetadataTokens.Handle(operand);
                    if(handle.Kind==HandleKind.FieldDefinition) {
                        var field=md.GetFieldDefinition((FieldDefinitionHandle)handle);
                        if(fields.TryGetValue((FieldDefinitionHandle)handle,out var known)) push(known);
                        else push(TypedObj(field.DecodeSignature(Signatures,null)));
                    }
                    else if(handle.Kind==HandleKind.MemberReference) {
                        var member=md.GetMemberReference((MemberReferenceHandle)handle);
                        var owner=Static(member.Parent);
                        if(owner.type=="System.Type" && md.GetString(member.Name)=="EmptyTypes") push(new Arr());
                        else push(TypedObj(member.DecodeFieldSignature(Signatures,null)));
                    }
                    else push(Unknown.Instance);
                    continue;
                }
                if(name=="ldfld") {
                    var owner=pop();
                    var handle=(EntityHandle)MetadataTokens.Handle(operand);
                    string memberName=handle.Kind==HandleKind.MemberReference?md.GetString(md.GetMemberReference((MemberReferenceHandle)handle).Name):null;
                    if(memberName!=null && memberName.StartsWith("Item",StringComparison.Ordinal) && int.TryParse(memberName.Substring(4),out int slot)) {
                        if(owner is Tuple tuple && slot<=tuple.Items.Length) { push(tuple.Items[slot-1]); continue; }
                        if(owner is Each each && each.Field<0) { push(new Each { Items=each.Items, Field=slot-1 }); continue; }
                    }
                    if(handle.Kind==HandleKind.FieldDefinition) push(TypedObj(md.GetFieldDefinition((FieldDefinitionHandle)handle).DecodeSignature(Signatures,null)));
                    else if(handle.Kind==HandleKind.MemberReference) push(TypedObj(md.GetMemberReference((MemberReferenceHandle)handle).DecodeFieldSignature(Signatures,null)));
                    else push(Unknown.Instance);
                    continue;
                }
                if(name=="castclass" || name=="unbox.any" || name=="constrained." || name=="readonly." || name=="tail." || name=="volatile." || name=="box") {
                    if(name=="castclass" || name=="unbox.any") {
                        var st=Static((EntityHandle)MetadataTokens.Handle(operand)); var top=pop();
                        push(st.type!=null && !(top is Member) && !(top is Ty)?new Obj { Type=st.type, Assembly=st.assembly }:top);
                    }
                    continue;
                }
                if(name=="isinst") { var top=pop(); push(top); continue; }
                if(name=="call" || name=="callvirt" || name=="newobj") { Call(name,(EntityHandle)MetadataTokens.Handle(operand),stack,pop,push,summary,site); continue; }
                if(name=="calli") { stack.Clear(); push(Unknown.Instance); continue; }
                if(name=="ret") { if(sig.ReturnType!="System.Void" && stack.Count>0) { var value=stack[stack.Count-1]; if(!(value is Null) && !(value is Unknown)) summary.Return=value; } stack.Clear(); stopped=true; continue; }
                if(name.StartsWith("ldelem",StringComparison.Ordinal)) {
                    var index=pop(); var array=pop();
                    if(array is Each row && row.Field<0 && index is Int cell) push(new Each { Items=row.Items, Field=cell.Value });
                    else if(array is Arr || array is Each || array is Param) { if(index is Int i && array is Arr known && known.Items.TryGetValue(i.Value,out var item)) push(item); else push(new Each { Items=array }); }
                    else push(Unknown.Instance);
                    continue;
                }
                int popCount=Pops(op.StackBehaviourPop), pushCount=Pushes(op.StackBehaviourPush);
                for(int i=0;i<popCount;i++) pop();
                for(int i=0;i<pushCount;i++) push(Unknown.Instance);
            }
            return summary;
        }
