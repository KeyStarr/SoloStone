            while(il.RemainingBytes>0) {
                // A branch target after a jump or throw starts from what the branch carried. That is what makes "x ?? throw" and "a ? b : c" keep their value.
                if(atBranch.TryGetValue(il.Offset,out var carried)) {
                    if(stopped) { stack.Clear(); stack.AddRange(carried); }
                    // A merge of a ? b : c: both arms are real, so both are read, as an Each of two.
                    else if(carried.Count==stack.Count && stack.Count>0 && Key(carried[stack.Count-1])!=Key(stack[stack.Count-1])) {
                        var arm=carried[stack.Count-1]; var other=stack[stack.Count-1];
                        if(arm is Null || arm is Unknown) { }
                        else if(other is Null || other is Unknown) stack[stack.Count-1]=arm;
                        else { var both=new Arr(); both.Items[0]=arm; both.Items[1]=other; stack[stack.Count-1]=new Each { Items=both }; }
                    }
