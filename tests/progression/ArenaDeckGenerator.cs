using System.Globalization;
using System.Text;
using SabberStoneCore.Model;

// Generates data/npc/arena-decks-v1.json: the NPC decks of Arena (#6), drafted by the same offer rules the player drafts under
// (DraftRules) with the draft bot at mixed skill. Fixed seeds and no clock: the same code writes the same bytes.
//
//   dotnet ProgressionTests.dll --gen-arena-decks data/npc/arena-decks-v1.json
//
// Regenerate whenever DraftRules, DraftBot, arena-rules-v1.json or the active card pool change; ArenaChecks compares this output
// with the committed file, so a stale file fails the progression suite.
internal static class ArenaDeckGenerator
{
    internal const int DeckCount = 200;
    internal const int RootSeed = 0x41524e44;   // "ARND"
    // Drafter skill cycles through five levels, so every quality bucket holds weak and strong drafters and good luck alike.
    internal static readonly double[] Skills = { 0.15, 0.35, 0.55, 0.75, 0.95 };

    internal sealed class Row
    {
        public string Id = "", Hero = "", Class = "";
        public int Seed;
        public double Skill, Quality;
        public List<KeyValuePair<string, int>> Cards = new();
    }

    internal static List<Row> Decks()
    {
        var rules = DraftRules.Arena();
        var rows = new List<Row>();
        for (int i = 0; i < DeckCount; i++)
        {
            int seed = StableSeed.Derive(RootSeed, rules.Version, i);
            double skill = Skills[i % Skills.Length];
            var draft = DraftBot.Draft(seed, skill);
            rows.Add(new Row {
                Id = "npc-arena-" + (i + 1).ToString("0000", CultureInfo.InvariantCulture), Hero = draft.Hero,
                Class = LocalDecks.HeroClass(draft.Hero).ToString(), Seed = seed, Skill = skill,
                Quality = Math.Round(draft.Quality, 4, MidpointRounding.AwayFromZero),
                Cards = draft.Deck.GroupBy(id => id, StringComparer.Ordinal).OrderBy(group => group.Key, StringComparer.Ordinal)
                    .Select(group => new KeyValuePair<string, int>(group.Key, group.Count())).ToList()
            });
        }
        return rows;
    }

    private static string Number(double value) => value.ToString("0.####", CultureInfo.InvariantCulture);

    internal static string Json()
    {
        var rows = Decks();
        var order = rows.OrderBy(row => row.Quality).ThenBy(row => row.Id, StringComparer.Ordinal).ToList();
        var text = new StringBuilder();
        text.Append("{\n \"schema\": 1,\n \"libraryVersion\": 1,\n \"activeMeta\": \"violet-hold\",\n");
        text.Append(" \"_doc\": \"SoloStone Arena NPC decks (#6): drafted by the draft bot under the same offer rules as the player (DraftRules, rulesVersion 1),");
        text.Append(" fixed seeds, drafter skill cycling 0.15-0.95. Admission arena: never served by the ladder, Casual or deck inference. Generated by");
        text.Append(" tests/progression/ArenaDeckGenerator.cs; do not edit by hand. quality = the drafter's mean pick score.\",\n");
        text.Append(" \"decks\": [\n");
        for (int i = 0; i < rows.Count; i++)
        {
            var row = rows[i];
            int tier = 5 - Math.Min(4, order.IndexOf(row) * 5 / rows.Count);   // 1 = top fifth by quality ... 5 = bottom fifth
            text.Append("  {\"id\": \"").Append(row.Id).Append("\", \"version\": 1, \"name\": \"Arena Draft ").Append(i + 1)
                .Append("\", \"class\": \"").Append(row.Class).Append("\", \"hero\": \"").Append(row.Hero)
                .Append("\", \"origin\": \"arena-drafted\", \"admission\": \"arena\", \"rulesVersion\": 1, \"seed\": ").Append(row.Seed.ToString(CultureInfo.InvariantCulture))
                .Append(", \"skill\": ").Append(Number(row.Skill)).Append(", \"quality\": ").Append(Number(row.Quality))
                .Append(",\n   \"tags\": {\"archetype\": \"midrange\", \"powerTier\": ").Append(tier)
                .Append(", \"pilotDifficulty\": 3, \"annoyance\": 0, \"fun\": 3, \"bands\": [\"bronze\", \"legend\"]},\n")
                .Append("   \"source\": {\"site\": \"solostone\", \"url\": null, \"accessed\": \"2026-11-15\", \"deckCode\": null, \"changes\": \"drafted by the draft bot\"},\n")
                .Append("   \"cards\": [").Append(string.Join(", ", row.Cards.Select(card => "{\"id\": \"" + card.Key + "\", \"count\": " + card.Value + "}")))
                .Append("]}").Append(i + 1 < rows.Count ? "," : "").Append('\n');
        }
        text.Append(" ]\n}\n");
        return text.ToString();
    }

    internal static void Write(string path) => File.WriteAllBytes(path, new UTF8Encoding(false).GetBytes(Json()));
}
