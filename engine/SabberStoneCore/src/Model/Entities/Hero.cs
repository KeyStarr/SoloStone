		/// <summary>Gets or sets the hero power entity.</summary>
		/// <value><see cref="Entities.HeroPower"/></value>
		private HeroPower _heroPower;
        public HeroPower HeroPower
        {
            get => _heroPower;
            set { if (_heroPower != value) Actions.BasicHeroPowerRules.DetachPassive(_heroPower); _heroPower = value; if (value != null) Actions.CostRules.RefreshHandAuras(Game); }
        }

		/// <summary>Gets or sets the weapon entity equipped on the Hero.</summary>
		/// <value><see cref="Entities.Weapon"/></value>
		public Weapon Weapon { get; set; }

        internal void ResolveFullHealthGrants()
        {
            if (!ReferenceEquals(Controller.Hero, this) || Health <= 0 || ToBeDestroyed || Damage != 0) return;
            var grants = AppliedEnchantments?.Where(e => e.Card.Id == "CATA_307e").ToArray();
            if (grants == null || grants.Length == 0) return;
            // Consume the whole eligible set before damage can cause nested health transitions.
            foreach (var grant in grants) grant.Remove();
            foreach (var grant in grants) Controller.Opponent.Hero.TakeDamage(grant, 15);
        }

		public List<Aura> Auras { get; }

		/// <summary>Initializes a new instance of the <see cref="Hero"/> class.</summary>
		/// <param name="controller">Owner of the character; not specifically limited to players.</param>
		/// <param name="card">The card which this character embodies.</param>
		/// <param name="tags">Properties of this entity.</param>
		/// <autogeneratedoc />
		public Hero(in Controller controller, in Card card, in IDictionary<GameTag, int> tags, in int id = -1)
			: base(in controller, in card, in tags, in id)
		{
			Auras = new List<Aura>();
			Game.Log(LogLevel.VERBOSE, BlockType.PLAY, "Hero", !Game.Logging? "":$"{card.Name} ({card.Class}) was created.");
		}

		/// <summary>
		/// A copy constructor.
		/// </summary>
		/// <param name="controller">The target <see cref="T:SabberStoneCore.Model.Entities.Controller" /> instance.</param>
		/// <param name="hero">The source <see cref="T:SabberStoneCore.Model.Entities.Hero" />.</param>
		private Hero(in Controller controller, Hero hero) : base(in controller, hero)
		{
			Auras = new List<Aura>(hero.Auras.Count);
			DamageTakenThisTurn = hero.DamageTakenThisTurn;
			_extraAttacksThisTurn = hero._extraAttacksThisTurn;
		}

#pragma warning disable CS1591 // Missing XML comment for publicly visible type or member

		public override int AttackDamage => Actions.DamageArithmetic.Add(base.AttackDamage, Game.CurrentPlayer != Controller ? 0 : Weapon?.AttackDamage ?? 0);

		public int TotalAttackDamage => AttackDamage/* + (Weapon?.AttackDamage ?? 0)*/;

		public override bool CanAttack
			=> AttackDamage > 0
			   && (!IsExhausted
                   || (_extraAttacksThisTurn > 0 && _extraAttacksThisTurn >= _numAttackThisTurn))
			   && !IsFrozen
			   && HasAnyValidAttackTargets;

        internal void CarryAttackStateFrom(Hero previous)
        {
            NumAttacksThisTurn = previous.NumAttacksThisTurn;
            ExtraAttacksThisTurn = previous.ExtraAttacksThisTurn;
            IsExhausted = previous.IsExhausted;
        }

		public override bool HasWindfury
		{
			get => this[GameTag.WINDFURY] > 0 || (Weapon?.IsWindfury ?? false);
			set => this[GameTag.WINDFURY] = value ? 1 : 0;
		}

		private bool _equippingWeapon;

		// No unlimited-attacks tag exists; legacy weapons use this unconditional, repeatable hero-ready trigger.
		private bool HasUnlimitedWeaponAttacks => Weapon != null && Weapon[GameTag.SILENCED] == 0
			&& Weapon.Card.Power?.Trigger is
			{
				Type: TriggerType.AFTER_ATTACK, TriggerSource: TriggerSource.HERO,
				TriggerActivation: TriggerActivation.PLAY, Condition: null, RemoveAfterTriggered: false,
				SingleTask: SetGameTagTask { Tag: GameTag.EXHAUSTED, Amount: 0, Type: EntityType.HERO }
			};

		internal int AttackLimit => HasUnlimitedWeaponAttacks ? int.MaxValue : this[GameTag.MEGA_WINDFURY] > 0 ? 4 : HasWindfury ? 2 : 1;

		internal void UpdateAttackReadinessAfterAttackLimitChange(int previousLimit)
		{
			if (_equippingWeapon || previousLimit == AttackLimit) return;
			if (NumAttacksThisTurn >= 1)
				IsExhausted = NumAttacksThisTurn >= AttackLimit;
		}

		public override bool HasLifeSteal => this[GameTag.LIFESTEAL] > 0 || (Weapon?.HasLifeSteal ?? false);

		public override bool IsImmune
		{
			get => (AuraEffects?.Immune > 0) || base.IsImmune;
			set => base.IsImmune = value;
		}

		public override bool HasOverkill => Weapon?.HasOverkill ?? false;

		public void AddWeapon(Weapon weapon)
		{
			int previousLimit = AttackLimit;
			// Replacement is one attack-limit transition, including removal of the old enchantments.
			_equippingWeapon = true;
			try
			{
				RemoveWeapon();
				weapon.OrderOfPlay = Game.NextOop;
				Weapon = weapon;
				Weapon[GameTag.ZONE] = (int)Enums.Zone.PLAY;
				Weapon[GameTag.ZONE_POSITION] = 0;
				EquippedWeapon = weapon.Id;
			}
			finally
			{
				_equippingWeapon = false;
				UpdateAttackReadinessAfterAttackLimitChange(previousLimit);
			}

			Game.TriggerManager.OnEquipWeaponTrigger(weapon);
		}

		/// <summary>
		/// Removes the equipped weapon to the graveyard. This triggers deathrattle events on the weapon.
		/// </summary>
		public void RemoveWeapon()
		{
			if (Weapon == null)
				return;

			if (Weapon.HasDeathrattle)
				Weapon.ActivateTask(PowerActivation.DEATHRATTLE);

			Game.TriggerManager.OnDeathTrigger(Weapon);

			Game.Log(LogLevel.INFO, BlockType.PLAY, "Hero", !Game.Logging? "":$"Butcher's knife incoming to graveyard, say 'gugus' to {Weapon}");
			Controller.GraveyardZone.Add(Weapon);

			ClearWeapon();
		}

		/// <summary>
		/// Clears weapon information on Hero.
		/// </summary>
		public void ClearWeapon()
		{
			int previousLimit = AttackLimit;
            Actions.PayloadRules.WeaponRemoved(Weapon);
			Weapon.ActivatedTrigger?.Remove();
			Weapon.OngoingEffect?.Remove();
			if (Weapon.AppliedEnchantments != null && Weapon[GameTag.KEEP_ENCHANTMENTS] != 1)
				for (int i = Weapon.AppliedEnchantments.Count - 1; i >= 0; i--)
					Weapon.AppliedEnchantments[i].Remove();
			Weapon = null;
			EquippedWeapon = 0;
			UpdateAttackReadinessAfterAttackLimitChange(previousLimit);
		}

		public override IPlayable Clone(in Controller controller)
		{
			return new Hero(in controller, this);
		}

		public string FullPrint()
		{
			var str = new StringBuilder();
			string mStr = Weapon != null ? $"[{Weapon.Card.Name}[{Weapon.AttackDamage}/{Weapon.Durability}]]" : "[NO WEAPON]";
			str.Append($"[HERO][{this}][ATK{AttackDamage}/AR{Armor}/HP{Health}][WP{mStr}][SP{Controller.CurrentSpellPower}]");
			//str.Append($"[ENCH {OldEnchants.Count}]");
			//str.Append($"[TRIG {Triggers.Count}]");
			return str.ToString();
		}

