        public static string Half(Card card, bool top) => Entries[card.Id].Text.Split('&')[top ? 0 : 1];
        public static string Normalize(string text) => Regex.Replace(
            Regex.Replace(text ?? "", @"<[^>]*>|\[x\]|_", " "), @"\s+", " ").Trim();

        public static bool Supports(Card card) => card != null && card.Implemented && Executable.Contains(card.Id)
            && Entries.TryGetValue(card.Id, out var entry) && entry.DbfId == card.AssetId && Payload(card) != null;

        private static string Header(Card card) => Normalize(Half(card, true));
        public static bool HasBattlecry(Card card) => Header(card).Contains("Battlecry");
        public static bool HasDeathrattle(Card card) => Header(card).Contains("Deathrattle");
        public static bool HasOwnerEnd(Card card) => Header(card).Contains("At the end of your turn,");

        internal static ISimpleTask Payload(Card card) => HasBattlecry(card) ? card.Power?.PowerTask
            : HasDeathrattle(card) ? card.Power?.DeathrattleTask : card.Power?.Trigger?.SingleTask;

        internal static Power ComposePower(Card top, Card bottom)
        {
            var summon = Actions.AssembleRules.SummonCallback(bottom);
            var payload = summon != null ? new CustomTask(summon)
                : Payload(bottom) ?? throw new ArgumentException("Missing split payload.");
            var power = new Power();
            if (HasBattlecry(top)) power.PowerTask = payload;
            if (HasDeathrattle(top)) power.DeathrattleTask = payload;
            if (top.Power.Trigger != null)
            {
                var trigger = top.Power.Trigger;
                power.Trigger = new Trigger(trigger.Type) {
                    TriggerSource = trigger.TriggerSource, TriggerActivation = trigger.TriggerActivation,
                    Condition = trigger.Condition, EitherTurn = trigger.EitherTurn,
                    FastExecution = trigger.FastExecution, RemoveAfterTriggered = trigger.RemoveAfterTriggered,
                    OrderDeathByPlay = trigger.OrderDeathByPlay, SingleTask = payload
                };
            }
            return power;
        }
