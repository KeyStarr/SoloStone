using System;
using System.Collections.Generic;
using System.Linq;
using SabberStoneCore.Conditions;
using SabberStoneCore.Enchants;
using SabberStoneCore.Enums;
using SabberStoneCore.Model;
using SabberStoneCore.Model.Entities;
using SabberStoneCore.Tasks;
using SabberStoneCore.Tasks.SimpleTasks;
using SabberStoneCore.Triggers;

namespace SabberStoneCore.CardSets.Client.Adventures.DungeonRun
{
    // Dungeon Run's final (round 8) bosses (https://hearthstone.wiki.gg/wiki/Dungeon_Run): 70 Health, two Mana Crystals at the
    // start (the run's fight rules). Special starts come from the content file: Vustrasz's five Master Chests (starting
    // board), the player's three Luminous Candles against The Darkness (starting hand).
    internal static class DungeonRunFinals
    {
        private const string MasterChest = "LOOT_357l", Darkspawn = "LOOTA_BOSS_49t";

        // King Togwaggle's Magic Candle: the treasures it can find (https://hearthstone.wiki.gg/wiki/King_Togwaggle_(boss),
        // "Not every Treasure card can be generated by King Togwaggle's Hero Power. This is a list of potential outcomes.").
        private static readonly string[] TogwaggleTreasures = {
            "LOOTA_819", "LOOTA_836", "LOOTA_823", "LOOTA_812", "LOOTA_838", "LOOTA_827", "LOOT_998k", "LOOTA_835",
            "LOOTA_847", "LOOTA_816", "LOOTA_826", "LOOTA_839", "LOOTA_843", "LOOTA_821", "LOOTA_806", "LOOTA_842b"
        };

        private static readonly string[] Beams = {
            "LOOTA_BOSS_26p2", "LOOTA_BOSS_26p3", "LOOTA_BOSS_26p4", "LOOTA_BOSS_26p5", "LOOTA_BOSS_26p6", "LOOTA_BOSS_26p7"
        };

        internal static void Apply(Action<int, string, Action<Card>> register)
        {
            // Azari, the Devourer. Devour (0, autocast): Remove the top 2 cards of your opponent's deck.
            register(46352, "LOOTA_BOSS_34h", DungeonRunCards.Plain);
            register(46353, "LOOTA_BOSS_34p", card => {
                card.PlayAvailabilityPredicate = (c, _) => !c.Opponent.DeckZone.IsEmpty;
                Untargeted(card, new EnqueueTask(2, new MoveToGraveYard(EntityType.OP_TOPDECK)));
            });

            // The Darkness. Encroaching Darkness (0, autocast): Summon a 5/5 Darkspawn. The player starts with three Luminous
            // Candles (Destroy all Darkspawns).
            register(47333, "LOOTA_BOSS_49h", DungeonRunCards.Plain);
            register(47332, "LOOTA_BOSS_49p", card => {
                card.SetPlayRequirements(new Dictionary<PlayReq, int> { { PlayReq.REQ_NUM_MINION_SLOTS, 1 } });
                Untargeted(card, new SummonTask(Darkspawn));
            });
            register(47330, Darkspawn, DungeonRunCards.Plain);
            register(47331, "LOOTA_BOSS_49t2", card => Untargeted(card, ComplexTask.Create(
                new IncludeTask(EntityType.ALLMINIONS),
                new FilterStackTask(new SelfCondition(p => p.Card.Id == Darkspawn)),
                new DestroyTask(EntityType.STACK))));

            // Vustrasz the Ancient: starts with five Master Chests (each gives the player a treasure when it dies). Vindictive
            // Breath (0, autocast): Deal 1 damage to all enemies for each missing Master Chest.
            register(46349, "LOOTA_BOSS_25h", DungeonRunCards.Plain);
            register(46350, "LOOTA_BOSS_25p", card => {
                card.PlayAvailabilityPredicate = (c, _) => MissingChests(c) > 0;
                Untargeted(card, ComplexTask.Create(
                    new FuncNumberTask(p => MissingChests(p.Controller)),
                    new DamageNumberTask(EntityType.ENEMIES)));
            });
            // Chromatic Dragonkin (Blackwing Lair adventure; in Vustrasz's deck): Whenever your opponent casts a spell, gain
            // +2/+2.
            register(2437, "BRMA12_8t", card => {
                card.Power = new Power {
                    Trigger = new Trigger(TriggerType.CAST_SPELL) {
                        TriggerSource = TriggerSource.ENEMY,
                        SingleTask = new AddEnchantmentTask("BRMA12_8te", EntityType.SOURCE)
                    }
                };
                DungeonRunCards.Plain(card);
            });
            register(39810, "BRMA12_8te", card => Enchantment(card, Effects.AttackHealth_N(2)));

            // King Togwaggle. Magic Candle (3): Find a Treasure! (a random one of the sixteen the wiki lists).
            register(47210, "LOOTA_BOSS_99h", DungeonRunCards.Plain);
            register(47209, "LOOTA_BOSS_99p", card => {
                card.PlayAvailabilityPredicate = (c, _) => !c.HandZone.IsFull;
                Untargeted(card, AddRandom(TogwaggleTreasures));
            });
            // Rakanishu (0): Deal 4 damage to a random enemy. The wiki lists it among Togwaggle's special cards but not how he
            // gets it (it is in neither his deck list nor the treasure list), so nothing generates it yet.
            register(48824, "LOOTA_BOSS_99t", card => Untargeted(card, ComplexTask.Create(
                new RandomTask(1, EntityType.ENEMIES),
                new DamageTask(4, EntityType.STACK, true))));

            // Xol the Unscathed. Beam Me Up! (passive): At the end of your turn, add a random Beam to your hand.
            register(47410, "LOOTA_BOSS_26h", DungeonRunCards.Plain);
            register(47428, "LOOTA_BOSS_26p8", card => {
                Actions.PassiveHeroPowerRules.Mark(card);
                card.Power = new Power { Trigger = new Trigger(TriggerType.TURN_END) { SingleTask = AddRandomBeam() } };
                DungeonRunCards.Plain(card);
            });
            // Beam of Frost (3): Freeze a random enemy minion and the minions next to it.
            register(47409, "LOOTA_BOSS_26p2", card => Beam(card, true, ComplexTask.Create(
                RandomEnemyAndNeighbours(),
                ComplexTask.Freeze(EntityType.STACK))));
            // Beam of Death (3): Destroy all damaged enemy minions.
            register(47411, "LOOTA_BOSS_26p3", card => Beam(card, false, ComplexTask.Create(
                new IncludeTask(EntityType.OP_MINIONS),
                new FilterStackTask(SelfCondition.IsDamaged),
                new DestroyTask(EntityType.STACK))));
            // Beam of Confusion (3): Take control of a random enemy minion.
            register(47412, "LOOTA_BOSS_26p4", card => {
                Beam(card, true, ComplexTask.Create(new RandomTask(1, EntityType.OP_MINIONS), new ControlTask(EntityType.STACK)));
                card.SetPlayRequirements(new Dictionary<PlayReq, int> {
                    { PlayReq.REQ_MINIMUM_ENEMY_MINIONS, 1 }, { PlayReq.REQ_NUM_MINION_SLOTS, 1 } });
            });
            // Beam of Fear (3): Shuffle a random enemy minion into your opponent's deck.
            register(47413, "LOOTA_BOSS_26p5", card => Beam(card, true, ComplexTask.Create(
                new RandomTask(1, EntityType.OP_MINIONS),
                new MoveToDeck(EntityType.STACK, opponent: true))));
            // Beam of Fire (3): Deal 2 damage to all enemy minions.
            register(47414, "LOOTA_BOSS_26p6", card => Beam(card, false, new DamageTask(2, EntityType.OP_MINIONS, true)));
            // Beam of Decay (3): Destroy 1 of your opponent's Mana Crystals (a spent one first).
            register(47415, "LOOTA_BOSS_26p7", card => Beam(card, false, new CustomTask((game, controller, source, target, stack) => {
                var opponent = controller.Opponent;
                if (opponent.BaseMana == 0) return;
                Actions.Generic.ChangeManaCrystal(opponent, -1, true);
                if (opponent.UsedMana > 0) opponent.UsedMana--;
            })));
        }

        // A random enemy minion and the ones next to it, onto the stack.
        private static ISimpleTask RandomEnemyAndNeighbours() => new CustomTask((game, controller, source, target, stack) => {
            var board = controller.Opponent.BoardZone;
            var picked = new List<IPlayable>();
            var candidates = board.Where(m => !m.Untouchable).ToList();
            if (candidates.Count > 0)
            {
                Minion centre = candidates[DungeonRunCards.Pick(game, candidates.Count)];
                int pos = centre.ZonePosition;
                if (pos > 0 && !board[pos - 1].Untouchable) picked.Add(board[pos - 1]);
                picked.Add(centre);
                if (pos < board.Count - 1 && !board[pos + 1].Untouchable) picked.Add(board[pos + 1]);
            }
            stack.Playables = picked;
        });

        private static int MissingChests(Controller controller) =>
            Math.Max(0, 5 - controller.BoardZone.Count(m => m.Card.Id == MasterChest));

        private static ISimpleTask AddRandomBeam() => AddRandom(Beams);

        // A random one of the cards into the hand, shown as created by the source.
        private static ISimpleTask AddRandom(string[] ids) => new CustomTask((game, controller, source, target, stack) => {
            if (controller.HandZone.IsFull) return;
            var card = Entity.FromCard(controller, Cards.FromId(ids[DungeonRunCards.Pick(game, ids.Length)]));
            card[GameTag.DISPLAYED_CREATOR] = source.Id;
            Actions.Generic.AddHandPhase.Invoke(controller, card);
        });

        private static void Beam(Card card, bool needsEnemyMinion, ISimpleTask task)
        {
            if (needsEnemyMinion)
                card.SetPlayRequirements(new Dictionary<PlayReq, int> { { PlayReq.REQ_MINIMUM_ENEMY_MINIONS, 1 } });
            card.Power = new Power { PowerTask = task };
            DungeonRunCards.Plain(card);
        }

        private static void Untargeted(Card card, ISimpleTask task)
        {
            card.Power = new Power { PowerTask = task };
            DungeonRunCards.Plain(card);
        }

        private static void Enchantment(Card card, params IEffect[] effects)
        {
            card.Power = new Power { Enchant = new Enchant(effects) };
            DungeonRunCards.Plain(card);
        }
    }
}
