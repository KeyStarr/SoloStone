    {
        [StandardCard("MEND_304", 123492)]
        internal static void Configure(Card card)
        {
            card.Implemented = true; card.ExcludeFromLegacyRandomPools = true;
            card.Power = new Power { PowerTask = new CustomTask((g,c,s,t,stack) => c[CompanionRules.ExtraSummons]++) };
        }
    }
